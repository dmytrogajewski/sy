#!/usr/bin/env python3
"""Generate llms-full.txt from README.md and the Markdown links in llms.txt."""

from __future__ import annotations

import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / "llms.txt"
OUTPUT = ROOT / "llms-full.txt"
LINK = re.compile(r"^\s*- \[[^]]+\]\(([^)]+\.md)(?:#[^)]*)?\)")
HEADING = re.compile(r"^(#{1,6})(\s+.*)$")


def source_paths() -> list[str]:
    paths = ["README.md"]
    for line in INDEX.read_text(encoding="utf-8").splitlines():
        match = LINK.match(line)
        if not match:
            continue
        parsed = urlsplit(match.group(1))
        path = unquote(parsed.path)
        if path and path not in paths and (ROOT / path).is_file():
            paths.append(path)
    return paths


def demote_headings(markdown: str) -> str:
    result: list[str] = []
    fence: str | None = None
    for line in markdown.splitlines():
        marker = re.match(r"^\s*(```+|~~~+)", line)
        if marker:
            token = marker.group(1)[0]
            if fence is None:
                fence = token
            elif fence == token:
                fence = None
        if fence is None:
            heading = HEADING.match(line)
            if heading:
                line = f"#{heading.group(1)}{heading.group(2)}"
        result.append(line)
    return "\n".join(result).rstrip() + "\n"


def render() -> str:
    sections = [
        "<!-- Generated by scripts/generate-llms-full.py from llms.txt. Do not edit by hand. -->",
        "# Full text for sy documentation",
    ]
    for path in source_paths():
        content = (ROOT / path).read_text(encoding="utf-8")
        sections.append(f"# Source: {path}\n\n{demote_headings(content)}")
    return "\n\n".join(sections)


def main() -> None:
    generated = render()
    if len(sys.argv) == 2 and sys.argv[1] == "--check":
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("llms-full.txt is stale; run python3 scripts/generate-llms-full.py")
        return
    if len(sys.argv) > 1:
        raise SystemExit("usage: generate-llms-full.py [--check]")
    OUTPUT.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
